import 'dart:math';
import 'package:sqflite/sqflite.dart';
import 'package:supabase_flutter/supabase_flutter.dart';
import 'database_helper.dart';
import 'organization.dart';

class OrganizationRepository {
  final _supabase = Supabase.instance.client;
  final dbHelper = DatabaseHelper.instance;

  /// Generates a random 9-character alphanumeric organization code.
  String generateOrganizationCode() {
    final random = Random();
    const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
    return List.generate(9, (index) => chars[random.nextInt(chars.length)]).join();
  }

  /// Syncs an organization to Supabase (required) and caches it locally.
  Future<Organization> createOrganization(Organization org) async {
    // 1. Try syncing to Supabase - this is MANDATORY for cloud-based registration
    try {
      final response = await _supabase
          .from('organizations')
          .insert(org.toMap()..remove('id'))
          .select()
          .single()
          .timeout(const Duration(seconds: 8));

      final supabaseOrg = Organization.fromMap(response);
      print('✅ Synced Organization to Supabase: ${supabaseOrg.name}');

      // 2. Save locally (using the ID generated by Supabase)
      final db = await dbHelper.database;
      await db.insert(
        'organizations',
        supabaseOrg.toMap(),
        conflictAlgorithm: ConflictAlgorithm.replace,
      );

      return supabaseOrg;
    } catch (e) {
      print('⚠️ Supabase Organization creation failed: $e');
      // Rethrow so the UI knows the registration/creation couldn't be completed in the cloud.
      // This prevents local-only organizations that students can't join.
      rethrow;
    }
  }

  /// Fetches an organization by its unique 9-character code.
  Future<Organization?> getOrganizationByCode(String code) async {
    final cleanCode = code.trim().toUpperCase();

    // 1. Try Supabase first
    try {
      final List<dynamic> response = await _supabase
          .from('organizations')
          .select()
          .eq('code', cleanCode)
          .timeout(const Duration(seconds: 8));

      if (response.isNotEmpty) {
        final org = Organization.fromMap(response.first as Map<String, dynamic>);
        // Cache locally
        final db = await dbHelper.database;
        await db.insert('organizations', org.toMap(), conflictAlgorithm: ConflictAlgorithm.replace);
        return org;
      }
    } catch (e) {
      print('⚠️ Supabase fetch organization by code error: $e');
    }

    // 2. Fallback to local db
    final db = await dbHelper.database;
    final List<Map<String, dynamic>> maps = await db.query(
      'organizations',
      where: 'code = ?',
      whereArgs: [cleanCode],
    );

    if (maps.isNotEmpty) {
      return Organization.fromMap(maps.first);
    }
    return null;
  }

  /// Fetches an organization by its ID.
  Future<Organization?> getOrganizationById(int id) async {
    // Try Supabase first
    try {
      final response = await _supabase
          .from('organizations')
          .select()
          .eq('id', id)
          .single()
          .timeout(const Duration(seconds: 8));

      final org = Organization.fromMap(response);
      final db = await dbHelper.database;
      await db.insert('organizations', org.toMap(), conflictAlgorithm: ConflictAlgorithm.replace);
      return org;
    } catch (e) {
      print('⚠️ Supabase fetch organization by ID error: $e');
    }

    // Fallback to local db
    final db = await dbHelper.database;
    final List<Map<String, dynamic>> maps = await db.query(
      'organizations',
      where: 'id = ?',
      whereArgs: [id],
    );

    if (maps.isNotEmpty) {
      return Organization.fromMap(maps.first);
    }
    return null;
  }

  /// Updates an organization's details in both Supabase and SQLite.
  Future<void> updateOrganizationDetails(int id, {
    String? name,
    String? address,
    String? country,
    String? type,
  }) async {
    final Map<String, dynamic> updates = {};
    if (name != null) updates['name'] = name.trim();
    if (address != null) updates['address'] = address.trim();
    if (country != null) updates['country'] = country.trim();
    if (type != null) updates['type'] = type.trim().toLowerCase();
    
    if (updates.isEmpty) return;

    // 1. Update in Supabase
    try {
      await _supabase
          .from('organizations')
          .update(updates)
          .eq('id', id)
          .timeout(const Duration(seconds: 8));
      print('✅ Updated organization details in Supabase: $updates');
    } on PostgrestException catch (e) {
      print('⚠️ Supabase Organization update error: $e');
      rethrow;
    } catch (e) {
      print('⚠️ Supabase Organization update offline/connection error: $e');
    }

    // 2. Update locally
    final db = await dbHelper.database;
    await db.update(
      'organizations',
      updates,
      where: 'id = ?',
      whereArgs: [id],
    );
  }
}
